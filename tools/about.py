#!/usr/bin/env python3
"""Bundle the About guide (ui/about/NN-slug.md) into ui/js/about-pages.js.

A file named NN-slug.md becomes the page about/slug, ordered by NN and titled by its first "# " heading.
Run this after changing any page; tests/suites/00-static.mjs checks that the bundle is current.
Usage: python3 tools/about.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'ui', 'about')
OUT = os.path.join(ROOT, 'ui', 'js', 'about-pages.js')

def pages():
    out = []
    for name in sorted(f for f in os.listdir(SRC) if re.match(r'^\d+-.+\.md$', f)):
        body = open(os.path.join(SRC, name), encoding='utf-8').read()
        slug = re.sub(r'^\d+-', '', name)[:-3]
        m = re.search(r'^# (.+)$', body, re.M)
        out.append({'slug': slug, 'title': m.group(1).strip() if m else slug, 'body': body})
    return out

def bundle():
    return ('// ---------- About guide pages (generated by tools/about.py from ui/about/*.md; do not edit) ----------\n'
            'const ABOUT_PAGES = ' + json.dumps(pages(), ensure_ascii=False, indent=0) + ';\n')

if __name__ == '__main__':
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(bundle())
    print(OUT)
